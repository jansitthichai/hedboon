export function buildUserPrompt(question: string, context: string): string {
  if (!context.trim()) {
    return [
      'สถานะคลังความรู้: ยังไม่พบชิ้นข้อมูลที่เกี่ยวข้องเพียงพอใน HedBoon',
      '',
      `คำถามผู้ใช้: ${question}`,
      '',
      'โปรดตอบในฐานะผู้เชี่ยวชาญ/ปราชญ์/หมอธรรมด้านประเพณีและงานบุญอีสาน โดยไม่ปฏิเสธผู้ถาม',
    ].join('\n')
  }

  return [
    'Retrieved Context (คลังความรู้ HedBoon):',
    context,
    '',
    `คำถามผู้ใช้: ${question}`,
    '',
    'จงตอบโดยยึด Context เป็นหลัก หากยังไม่ครบให้เสริมด้วยความรู้ผู้เชี่ยวชาญประเพณีอีสานอย่างชัดเจน',
  ].join('\n')
}
